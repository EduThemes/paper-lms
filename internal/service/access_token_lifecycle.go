// Personal access token lifecycle (G143): expiry, show, update and
// regenerate, matching Canvas's TokensController.

var (
	// ErrAccessTokenNotFound is returned when the token does not exist or
	// belongs to another user.
	ErrAccessTokenNotFound = errors.New("access token not found")
	// ErrAccessTokenExpiryInPast is returned for an expires_at that has
	// already passed.
	ErrAccessTokenExpiryInPast = errors.New("expires_at must be in the future")
	// ErrAccessTokenNotManual is returned when an operation only valid for
	// personal (manually generated) tokens targets an OAuth token.
	ErrAccessTokenNotManual = errors.New("only personal access tokens can be changed or regenerated")
	// ErrAccessTokenRegenerateExpired is returned when an expired token is
	// regenerated without a new expiry (Canvas refuses the same).
	ErrAccessTokenRegenerateExpired = errors.New("cannot regenerate an expired token without a new expiration date")
)

// ScopeAlwaysAllowed reports whether path may be called by any access
// token regardless of its scopes. Canvas lists only the token endpoint
// (so a scoped token can always revoke itself).
func ScopeAlwaysAllowed(path string) bool {
	path = strings.TrimSuffix(path, "/")
	return path == "/login/oauth2/token" || path == "/api/v1/login/oauth2/token"
}

// IsPersonalAccessToken reports whether the token was generated by the user
// (no developer key) rather than issued to an OAuth application.
func IsPersonalAccessToken(t *models.AccessToken) bool {
	return t != nil && t.DeveloperKeyID == nil
}

// AccessTokenExpired reports whether a personal access token is past its
// expiry. OAuth tokens' ExpiresAt is their hourly access expiry, refreshed
// with the refresh token, so they never count as permanently expired.
func AccessTokenExpired(t *models.AccessToken) bool {
	return IsPersonalAccessToken(t) && t.ExpiresAt != nil && time.Now().After(*t.ExpiresAt)
}

// CreatePersonalAccessTokenWithExpiry is CreatePersonalAccessToken with an
// optional permanent expiry (Canvas token[expires_at]).
func (s *AccessTokenService) CreatePersonalAccessTokenWithExpiry(ctx context.Context, userID uint, purpose string, scopes []string, expiresAt *time.Time) (*models.AccessToken, string, error) {
	if expiresAt != nil && !expiresAt.After(time.Now()) {
		return nil, "", ErrAccessTokenExpiryInPast
	}
	rawToken, err := generateRandomHex(32)
	if err != nil {
		return nil, "", errors.New("failed to generate token")
	}
	token := &models.AccessToken{
		UserID:        userID,
		Token:         hashToken(rawToken),
		TokenHint:     rawToken[len(rawToken)-4:],
		Scopes:        ScopesToJSON(scopes),
		Purpose:       purpose,
		ExpiresAt:     expiresAt,
		WorkflowState: "active",
	}
	if err := s.tokenRepo.Create(ctx, token); err != nil {
		return nil, "", err
	}
	return token, rawToken, nil
}

// FindUserToken loads one of userID's tokens by database id, or by its
// token_hint when that hint is unique among the user's tokens (Canvas
// accepts either in the URL).
func (s *AccessTokenService) FindUserToken(ctx context.Context, userID uint, idOrHint string) (*models.AccessToken, error) {
	if n, err := strconv.ParseUint(idOrHint, 10, 64); err == nil && n > 0 {
		t, err := s.tokenRepo.FindByID(ctx, uint(n))
		if err == nil && t != nil && t.UserID == userID {
			return t, nil
		}
		// A short numeric hint is also possible; fall through.
	}
	if idOrHint == "" {
		return nil, ErrAccessTokenNotFound
	}
	page, err := s.tokenRepo.ListByUserID(ctx, userID, repository.PaginationParams{Page: 1, PerPage: 1000})
	if err != nil {
		return nil, ErrAccessTokenNotFound
	}
	var match *models.AccessToken
	for i := range page.Items {
		if page.Items[i].TokenHint == idOrHint {
			if match != nil {
				return nil, ErrAccessTokenNotFound // ambiguous hint
			}
			match = &page.Items[i]
		}
	}
	if match == nil {
		return nil, ErrAccessTokenNotFound
	}
	return match, nil
}

// PersonalAccessTokenUpdate is a Canvas token[...] update. Nil fields are
// left unchanged; ClearExpiry removes the expiry.
type PersonalAccessTokenUpdate struct {
	Purpose     *string
	Scopes      *[]string
	ExpiresAt   *time.Time
	ClearExpiry bool
	Regenerate  bool
}

// UpdatePersonalAccessToken changes a personal access token and, with
// Regenerate, replaces its secret. The new raw token is returned only when
// regenerated (it is never stored).
func (s *AccessTokenService) UpdatePersonalAccessToken(ctx context.Context, token *models.AccessToken, u PersonalAccessTokenUpdate) (*models.AccessToken, string, error) {
	if !IsPersonalAccessToken(token) {
		return nil, "", ErrAccessTokenNotManual
	}
	if u.ExpiresAt != nil && !u.ExpiresAt.After(time.Now()) {
		return nil, "", ErrAccessTokenExpiryInPast
	}
	if u.Regenerate && AccessTokenExpired(token) && u.ExpiresAt == nil && !u.ClearExpiry {
		return nil, "", ErrAccessTokenRegenerateExpired
	}
	if u.Purpose != nil {
		token.Purpose = *u.Purpose
	}
	if u.Scopes != nil {
		token.Scopes = ScopesToJSON(*u.Scopes)
	}
	switch {
	case u.ClearExpiry:
		token.ExpiresAt = nil
	case u.ExpiresAt != nil:
		exp := *u.ExpiresAt
		token.ExpiresAt = &exp
	}
	raw := ""
	if u.Regenerate {
		var err error
		raw, err = generateRandomHex(32)
		if err != nil {
			return nil, "", errors.New("failed to generate token")
		}
		token.Token = hashToken(raw)
		token.TokenHint = raw[len(raw)-4:]
		token.LastUsedAt = nil
	}
	if err := s.tokenRepo.Update(ctx, token); err != nil {
		return nil, "", err
	}
	return token, raw, nil
}

// ListUserGeneratedTokens returns only the user's personal access tokens
// (Canvas GET /users/:user_id/user_generated_tokens).
func (s *AccessTokenService) ListUserGeneratedTokens(ctx context.Context, userID uint, params repository.PaginationParams) (*repository.PaginatedResult[models.AccessToken], error) {
	all, err := s.tokenRepo.ListByUserID(ctx, userID, repository.PaginationParams{Page: 1, PerPage: 1000})
	if err != nil {
		return nil, err
	}
	var personal []models.AccessToken
	for _, t := range all.Items {
		if IsPersonalAccessToken(&t) {
			personal = append(personal, t)
		}
	}
	if params.PerPage < 1 {
		params.PerPage = 10
	}
	if params.Page < 1 {
		params.Page = 1
	}
	start := (params.Page - 1) * params.PerPage
	if start > len(personal) {
		start = len(personal)
	}
	end := start + params.PerPage
	if end > len(personal) {
		end = len(personal)
	}
	return &repository.PaginatedResult[models.AccessToken]{
		Items:      personal[start:end],
		TotalCount: int64(len(personal)),
		Page:       params.Page,
		PerPage:    params.PerPage,
	}, nil
}
