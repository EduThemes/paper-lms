const TABLE: Record<Locale, Record<StringKey, string>> = { en, es, pt };

/** UI-facing starter copy for a locale (falls back to English). */
export function strings(locale: Locale): Record<string, string> {
  return { ...en, ...(TABLE[locale] ?? {}) };
}

/** Typed lookup with an optional early-elementary variant. */
export function t(locale: Locale, key: StringKey, young = false): string {
  const table = TABLE[locale] ?? en;
  if (young) {
    const yk = `${key}.young` as StringKey;
    if (yk in table) return table[yk];
  }
  return table[key] ?? en[key] ?? key;
}
